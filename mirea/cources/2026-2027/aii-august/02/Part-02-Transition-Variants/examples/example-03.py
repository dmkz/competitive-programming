# Читаем конечную точку:
n = int(input())
mod = 10 ** 9 + 7
# dp[i] — число последовательностей прыжков на 1 и 2 в точку i.
dp = [0] * (n + 1)
dp[0] = 1
for i in range(1, n + 1):
    dp[i] = dp[i - 1]
    if i >= 2: dp[i] = (dp[i] + dp[i - 2]) % mod
# Выводим количество маршрутов в конечную точку.
print(dp[n])